const normalize = (value) => value
  ? value
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .toLowerCase()
      .trim()
  : '';

// Resolve zone and region by state and municipio, case/diacritic insensitive
export const getZoneRegionByMunicipio = (state, municipio) => {
  const normState = normalize(state);
  const normMunicipio = normalize(municipio);

  const stateEntry = Object.entries(zoneRegionCatalog).find(([stateName]) => normalize(stateName) === normState);
  if (!stateEntry) return null;

  const [, zones] = stateEntry;
  for (const entry of zones) {
    if (entry.municipios.some(m => normalize(m) === normMunicipio)) {
      return { zone: entry.zone, region: entry.region };
    }
  }
  return null;
};
